import SwiftUI

struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    let text: String
    var date = Date()
    var pinned = false
}

/// Historique du presse-papiers (inspiré de Maccy). Texte uniquement, en mémoire ; seuls les éléments épinglés sont conservés.
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let maxItems = 60
    /// Types posés par les gestionnaires de mots de passe : jamais enregistrés.
    private static let ignoredTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                                    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    @Published var items: [ClipItem] = []
    @Published var enabled = UserDefaults.standard.object(forKey: "clipboardEnabled") as? Bool ?? true {
        didSet { UserDefaults.standard.set(enabled, forKey: "clipboardEnabled") }
    }
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private init() {
        if let d = UserDefaults.standard.data(forKey: "clipboardPinned"), let pinned = try? JSONDecoder().decode([ClipItem].self, from: d) {
            items = pinned
        }
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard enabled else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes),
              let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let pinned = items.first { $0.text == s }?.pinned ?? false
        items.removeAll { $0.text == s }
        items.insert(ClipItem(text: s, pinned: pinned), at: 0)
        trim()
    }

    private func trim() {
        var unpinned = 0
        items = items.filter { $0.pinned || { unpinned += 1; return unpinned <= Self.maxItems }() }
        savePinned()
    }

    private func savePinned() {
        if let d = try? JSONEncoder().encode(items.filter(\.pinned)) { UserDefaults.standard.set(d, forKey: "clipboardPinned") }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(of: item) else { return }
        items[i].pinned.toggle()
        savePinned()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        savePinned()
    }

    func clear() {
        items.removeAll { !$0.pinned }
        NSPasteboard.general.clearContents()
    }
}

struct ClipboardView: View {
    @ObservedObject var history = ClipboardHistory.shared
    @Local private var search = ""
    @Local private var copiedID: UUID?

    private var filtered: [ClipItem] {
        search.isEmpty ? history.items : history.items.filter { $0.text.localizedCaseInsensitiveContains(search) }
    }

    var body: some View {
        VStack(spacing: 0) {
            PageHeader(title: String(localized: "Presse-papiers"), subtitle: String(localized: "Retrouvez tout ce que vous avez copié"),
                       icon: "doc.on.clipboard.fill", color: .teal) {
                Toggle("Enregistrer l'historique", isOn: $history.enabled).toggleStyle(.switch)
            }
            HStack {
                TextField("Rechercher dans l'historique", text: $search).textFieldStyle(.roundedBorder)
                Button("Tout effacer (sauf épinglés)") { history.clear() }.disabled(history.items.isEmpty)
            }
            .padding(.horizontal, 24).padding(.bottom, 10)

            if filtered.isEmpty {
                EmptyState(icon: "doc.on.clipboard", title: history.items.isEmpty ? String(localized: "Historique vide") : String(localized: "Aucun résultat"),
                           message: String(localized: "Copiez du texte n'importe où (⌘C) : il apparaîtra ici. Les mots de passe copiés depuis un gestionnaire sont ignorés."))
            } else {
                List(filtered) { item in
                    HStack(alignment: .top, spacing: 10) {
                        Button { history.togglePin(item) } label: {
                            Image(systemName: item.pinned ? "pin.fill" : "pin").foregroundStyle(item.pinned ? .orange : .secondary)
                        }.buttonStyle(.borderless).help("Épingler")
                        VStack(alignment: .leading, spacing: 2) {
                            Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines)).lineLimit(3)
                            Text(item.date, format: .relative(presentation: .named)).font(.caption).foregroundStyle(.secondary)
                        }
                        Spacer()
                        Button(copiedID == item.id ? "Copié ✓" : "Copier") {
                            history.copy(item)
                            copiedID = item.id
                        }.controlSize(.small)
                        Button { history.remove(item) } label: { Image(systemName: "xmark") }.buttonStyle(.borderless)
                    }
                    .padding(.vertical, 2)
                }
                .listStyle(.inset(alternatesRowBackgrounds: true))
            }
            BottomBar {
                Image(systemName: "lock.shield").foregroundStyle(.secondary)
                Text("Texte uniquement, gardé en mémoire (seuls les éléments épinglés sont conservés). Accès rapide depuis la barre des menus.")
                    .font(.callout).foregroundStyle(.secondary)
                Spacer()
            }
        }
    }
}
